function changeLanguage(lang) {
  currentLang = lang;
  try { localStorage.setItem('aaguvenlik-lang', lang); } catch (e) {}
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    var key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      var text = translations[lang][key];
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.setAttribute('placeholder', text);
      } else if (el.tagName === 'META') {
        el.setAttribute('content', text);
      } else {
        el.innerHTML = text;
      }
    }
  });
  document.querySelectorAll('#subject option').forEach(function (opt, i) {
    var keys = ['form-subject-placeholder', 'form-subject1', 'form-subject2', 'form-subject3', 'form-subject4', 'form-subject5', 'form-subject6', 'form-subject7'];
    if (translations[lang] && translations[lang][keys[i]]) { opt.textContent = translations[lang][keys[i]]; }
  });
  document.querySelectorAll('.lang-btn').forEach(function (btn) {
    btn.classList.toggle('active-lang', btn.getAttribute('data-lang') === lang);
  });
  document.documentElement.setAttribute('lang', lang === 'tr' ? 'tr' : 'en');
  var pageKey = document.body.getAttribute('data-page');
  if (pageKey && translations[lang] && translations[lang][pageKey]) {
    document.title = translations[lang][pageKey] + ' | A&A Güvenlik';
  }
  var metaKey = document.body.getAttribute('data-meta-desc');
  var metaKeywordsKey = document.body.getAttribute('data-meta-keywords');
  var metaDesc = document.querySelector('meta[name="description"]');
  var metaKeywords = document.querySelector('meta[name="keywords"]');
  if (metaDesc && metaKey && translations[lang][metaKey]) { metaDesc.setAttribute('content', translations[lang][metaKey]); }
  if (metaKeywords && metaKeywordsKey && translations[lang][metaKeywordsKey]) { metaKeywords.setAttribute('content', translations[lang][metaKeywordsKey]); }
}

